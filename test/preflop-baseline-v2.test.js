import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { createHash } from 'node:crypto';
import { buildBaseline } from '../tools/build-preflop-baseline.js';
import { parsePreflopJson, lookup } from '../training/providers/preflop-json.js';
import { allHandClasses } from '../training/cards.js';
import { preflopKeys, parsePreflopKey, trainingPositionV2 } from '../shared/preflop-key.js';

test('v1 generator preserves the exact historical bytes and hash', () => {
  const bytes = `${JSON.stringify(buildBaseline(1))}\n`;
  assert.equal(bytes, fs.readFileSync(new URL('../training/data/preflop-baseline-v1.json', import.meta.url), 'utf8'));
  assert.equal(createHash('sha256').update(bytes).digest('hex'), '7df129ed8503a3df45058a13a52e05b1f8db8d8dd029dd65c31d98c94a9e9eaf');
});

test('v2 covers 99 distinct native contexts and all 169 hands with null EV', () => {
  const data = buildBaseline(2);
  assert.equal(Object.keys(data.spots).length, 99);
  const raw = `${JSON.stringify(data)}\n`;
  const parsed = parsePreflopJson(raw, { expectedSha256: createHash('sha256').update(raw).digest('hex') });
  for (const key of preflopKeys()) {
    assert.ok(parsePreflopKey(key));
    assert.deepEqual(Object.keys(data.spots[key]).sort(), allHandClasses().sort());
    for (const handClass of allHandClasses()) {
      const result = lookup(parsed, { spotKey: key, handClass });
      assert.equal(result.status, 'supported');
      assert.equal(Math.round(result.actions.reduce((n,a) => n+a.frequency,0)*10000),10000);
      assert.ok(result.actions.every(a=>a.evBb === null));
    }
  }
  assert.equal(preflopKeys().filter(k=>parsePreflopKey(k).context==='rfi-unopened').length,20);
});

test('position decoding depends on table size; keys reject impossible pairs', () => {
  assert.equal(trainingPositionV2('UTG+1', 6), 'HJ');
  assert.equal(trainingPositionV2('UTG+1', 9), 'UTG1');
  assert.equal(trainingPositionV2('UTG+4', 9), 'HJ');
  assert.equal(trainingPositionV2('UTG+2', 8), 'LJ');
  assert.equal(trainingPositionV2('UTG+4', 6), null);
  for (const key of ['9max-100bb-bb-rfi-v2','6max-100bb-utg-vs-hj-open25-v2','7max-100bb-btn-rfi-v2']) assert.equal(parsePreflopKey(key),null);
});

test('v2 validates exact completeness, action vocabulary, sizes and integer frequencies', () => {
  for (const mutate of [
    d=>delete d.spots['6max-100bb-hj-vs-utg-open25-v2'],
    d=>delete d.spots['6max-100bb-hj-rfi-v2'].AA,
    d=>d.spots['6max-100bb-hj-rfi-v2'].AA[0].action='jam',
    d=>d.spots['6max-100bb-hj-rfi-v2'].AA[0].sizeBb=99,
    d=>d.spots['6max-100bb-hj-rfi-v2'].AA[0].frequency=NaN,
  ]) {
    const data=buildBaseline(2);mutate(data);const raw=JSON.stringify(data);
    assert.throws(()=>parsePreflopJson(raw,{expectedSha256:createHash('sha256').update(raw).digest('hex')}),{code:'DATASET_INVALID'});
  }
});

test('v2 generated bytes and sidecar digest match the shipped registry', () => {
  const bytes = `${JSON.stringify(buildBaseline(2))}\n`;
  assert.equal(bytes, fs.readFileSync(new URL('../training/data/preflop-baseline-v2.json', import.meta.url), 'utf8'));
  const digest = createHash('sha256').update(bytes).digest('hex');
  assert.equal(digest, '1147b530a398c0b424379689d966d9be1fb60b665600b2600993689212fe02f7');
  assert.equal(fs.readFileSync(new URL('../training/data/preflop-baseline-v2.sha256', import.meta.url), 'utf8').trim().split(/\s+/)[0], digest);
});
