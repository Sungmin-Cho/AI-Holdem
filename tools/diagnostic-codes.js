/** A repository-defined code (or errno name) passes; anything else is 'UNLISTED'; absence is null. */
export function projectPublicCode(value) {
  if (value === undefined || value === null) return null;
  return typeof value === 'string' && PUBLIC.has(value) ? value : 'UNLISTED';
}
