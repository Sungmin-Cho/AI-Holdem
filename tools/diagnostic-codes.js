// A Set cannot be frozen against add(); the set stays private and the list is exported frozen.
const KNOWN = new Set(CODES);
export const RUN_DIAGNOSTIC_CODES = Object.freeze([...KNOWN]);

/** A listed code passes; any other value (string or not) is 'UNLISTED'; absence is null. */
export function projectDiagnosticCode(value) {
  if (value === undefined || value === null) return null;
  return typeof value === 'string' && KNOWN.has(value) ? value : 'UNLISTED';
}

