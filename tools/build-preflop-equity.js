// Builds training/data/preflop-equity-v1.js: seeded Monte Carlo all-in equity
// between all 169 preflop hand classes (6,000 runouts per pair, ~0.65%p error).
// `--check` rebuilds in memory and fails if the committed bytes differ.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { HAND_CLASSES } from '../shared/poker-eval.js';
import { EQUITY_SAMPLES_PER_PAIR, computePairEquityUnits } from '../training/ranges/equity-build.js';

export function buildEquityModule() {
  const n = HAND_CLASSES.length;
  let encoded = '';
  for (let i = 0; i < n; i += 1) {
    for (let j = i; j < n; j += 1) {
      const units = i === j ? 5000 : computePairEquityUnits(i, j);
      encoded += units.toString(36).padStart(3, '0');
    }
  }
  return `// Generated by tools/build-preflop-equity.js — do not edit by hand.\n`
    + `// Seeded Monte Carlo preflop all-in equity, ${EQUITY_SAMPLES_PER_PAIR} runouts per class pair.\n`
    + `export const PREFLOP_EQUITY_V1 = Object.freeze({ version: 1, samplesPerPair: ${EQUITY_SAMPLES_PER_PAIR}, encoded: '${encoded}' });\n`;
}

function main(argv) {
  const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../training/data/preflop-equity-v1.js');
  const check = argv.includes('--check');
  if (argv.some(arg => arg !== '--check')) throw new Error(`unknown argument: ${argv.find(arg => arg !== '--check')}`);
  const body = buildEquityModule();
  if (check) {
    if (fs.readFileSync(out, 'utf8') !== body) throw new Error('preflop equity table differs from a fresh build');
  } else {
    fs.writeFileSync(out, body);
  }
  process.stdout.write(`${JSON.stringify({ check, bytes: Buffer.byteLength(body) })}\n`);
}

if (process.argv[1] && fs.realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
